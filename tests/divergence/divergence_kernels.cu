/**
 * @file divergence_kernels.cu
 * @brief Warp divergence 测试 kernel — 每个lane将结果写到 buf[tid]
 *
 * 所有kernel用一个int*参数，32个int。每个lane = 32个threads，1 warp。
 * Host端读取buf[0..31]验证执行路径。
 */

// ====================================================================
// 1. 简单 if-else: tid==0 vs tid!=0
// ====================================================================
//   tid==0 → 100
//   tid!=0 → 200
// ====================================================================
__global__ void divergence_if_else(int* buf) {
    int tid = threadIdx.x;
    if (tid == 0)
        buf[tid] = 100;
    else
        buf[tid] = 200;
}

// ====================================================================
// 2. 多路分歧: tid < 8, 8 <= tid < 16, 16 <= tid < 24, 24 <= tid
// ====================================================================
//   0-7  → 10
//   8-15 → 20
//  16-23 → 30
//  24-31 → 40
// ====================================================================
__global__ void divergence_multi_path(int* buf) {
    int tid = threadIdx.x;
    if (tid < 8) {
        buf[tid] = 10;
    } else if (tid < 16) {
        buf[tid] = 20;
    } else if (tid < 24) {
        buf[tid] = 30;
    } else {
        buf[tid] = 40;
    }
}

// ====================================================================
// 3. 嵌套 if-else: 外层 <16 vs >=16，内层 <8 vs >=8
// ====================================================================
//   tid 0-7   → 1
//   tid 8-15  → 2
//   tid 16-31 → 3
// ====================================================================
__global__ void divergence_nested_if(int* buf) {
    int tid = threadIdx.x;
    if (tid < 16) {
        if (tid < 8)
            buf[tid] = 1;
        else
            buf[tid] = 2;
    } else {
        buf[tid] = 3;
    }
}

// ====================================================================
// 4. 循环内分歧: 0-15每轮+1, 16-31每轮+10, 5轮
// ====================================================================
//   tid 0-15  → 5   (5 * 1)
//   tid 16-31 → 50  (5 * 10)
// ====================================================================
__global__ void divergence_loop_if(int* buf) {
    int tid = threadIdx.x;
    int val = 0;
    for (int i = 0; i < 5; i++) {
        if (tid < 16)
            val += 1;
        else
            val += 10;
    }
    buf[tid] = val;
}

// ====================================================================
// 5. 不等长循环: 0-15 循环3次, 16-31 循环7次
// ====================================================================
//   tid 0-15  → tid * 3
//   tid 16-31 → tid * 7
// ====================================================================
__global__ void divergence_uneven_loop(int* buf) {
    int tid = threadIdx.x;
    int limit = (tid < 16) ? 3 : 7;
    int val = 0;
    for (int i = 0; i < limit; i++) {
        val += tid;
    }
    buf[tid] = val;
}

// ====================================================================
// 6. 混合: if-else + 循环 + if-else
// ====================================================================
//   先分歧, 然后循环(会合), 再分歧
//   tid 0-15:  val = tid + 100; loop(+1)*3 → tid+103; if even→*2, if odd→*3
//   tid 16-31: val = tid + 200; loop(+1)*3 → tid+203; if even→*2, if odd→*3
// ====================================================================
__global__ void divergence_mixed(int* buf) {
    int tid = threadIdx.x;
    int val = tid;

    // 第一次分歧
    if (tid < 16)
        val += 100;
    else
        val += 200;

    // 循环（会合点）
    for (int i = 0; i < 3; i++)
        val += 1;

    // 第二次分歧
    if (tid % 2 == 0)
        val *= 2;
    else
        val *= 3;

    buf[tid] = val;
}

// ====================================================================
// 7. 递归式分歧: 每一轮只有一半lane活跃
// ====================================================================
//   lane 0:   1轮 → 1
//   lane 1:   2轮 → 2
//   lane 3:   3轮 → 4
//   lane 7:   4轮 → 8
//   lane 15:  5轮 → 16
//   lane 31:  6轮 → 32
//   其它lane: 按最近的2^k-1计算
// ====================================================================
__global__ void divergence_reduction(int* buf) {
    int tid = threadIdx.x;
    int val = tid;
    // 每次只有低 tid 的lane继续
    for (int mask = 16; mask > 0; mask >>= 1) {
        if (tid < mask)
            val += 1;
    }
    buf[tid] = val;
}

// ====================================================================
// 8. 分歧 + barrier.sync 后恢复
// ====================================================================
//   tid<16 先写, barrier, tid>=16 再写(模拟分歧后同步)
// ====================================================================
__global__ void divergence_barrier_sync(int* buf) {
    __shared__ int shared_data[32];
    int tid = threadIdx.x;
    int lane = tid % 32;
    int value;
    if (tid < 16) {
        value = 100;
        for (int i = 0; i <= lane; i++) value += i;
    } else {
        value = 200;
        //buf[tid + 16] = tid + 200;
        for (int i = 1; i <= lane - 15; i++) value *= i;
    }
    __syncthreads();
    buf[tid] = value;
    // 所有lane同步后再次分歧
